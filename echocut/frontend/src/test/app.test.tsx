import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { MemoryRouter, Route, Routes } from "react-router-dom";
import { CreateProject } from "../pages/CreateProject";
import { Dashboard } from "../pages/Dashboard";
import { ExtractionReview } from "../pages/ExtractionReview";
import { Landing } from "../pages/Landing";
import { Projects } from "../pages/Projects";

function wrap(ui: React.ReactNode, path = "/") {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } });
  return render(<QueryClientProvider client={client}><MemoryRouter initialEntries={[path]}>{ui}</MemoryRouter></QueryClientProvider>);
}

afterEach(() => vi.restoreAllMocks());

test("landing page and accessible timeline render", () => {
  wrap(<Landing />);
  expect(screen.getByRole("heading", { name: /see your film/i })).toBeInTheDocument();
  expect(screen.getByRole("region", { name: /audience mind timeline/i })).toBeInTheDocument();
  expect(screen.getByText(/not generated by gemini/i)).toBeInTheDocument();
});

test("create project validates required fields", async () => {
  wrap(<CreateProject />);
  await userEvent.click(screen.getByRole("button", { name: "Create Project" }));
  expect(await screen.findByText("Film title is required")).toBeInTheDocument();
  expect(screen.getByText("Genre is required")).toBeInTheDocument();
});

